"""Relay 处理器侧的异常约定（投递层与消费层共享的唯一契约）。

为什么单独一个模块：``consumer`` 需要区分「处理器真的尝试过投递但失败」与
「处理器根本没外发（被熔断拦下）」——前者该计入事件重试次数，后者不该。
但 ``consumer`` 不能反向依赖 ``webhook``（webhook 已经依赖 consumer 的事件视图），
否则形成环。于是把这个判定挂在一个零依赖的错误基类上：

- ``DeliveryDeferredError``：**本次没有真正外发**。retry 语义不是「又失败一次」，
  而是「这轮没轮到它」，因此不递增 attempts、不写退避、更不推进死信。
- 其余异常仍按「一次失败尝试」处理（attempts+1、指数退避、达上限进死信）。

这条边界是审查 N2 的根因修复：把「熔断主动拦截」误当成「投递失败」，会在下游
短时故障时把一批从未外发的事件直接推成死信，违背 ADR-R13 的「事件不丢弃」。
"""

from __future__ import annotations


class OutboxDeliveryError(RuntimeError):
    """处理器侧投递异常的基类（方便接入方统一捕获与分类）。"""


class DeliveryDeferredError(OutboxDeliveryError):
    """本次未真正外发：不计入事件重试次数，等待下一轮再试。

    只应由处理器在「明确知道自己没有发出请求」时抛出（熔断拦截、并发闸门拒绝等）。
    误用（明明发了却抛它）会让毒事件无限重试——所以它是窄口语义，不是通用兜底。
    """
